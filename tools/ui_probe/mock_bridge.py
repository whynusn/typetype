"""由 bridge API 面自动生成 mock bridge QML。

mock bridge 是离屏加载时 ``appBridge`` 上下文属性的替身：每个 Property
生成带类型默认值的属性，每个 Slot 生成按返回注解的默认返回值，每个
Signal 生成同参数个数的 signal。QML 引用不存在的成员会在此暴露为加载
错误——这正是冒烟测试要抓的一类回归。

保真度要点（否则会产生隔离噪声，掩盖真实问题）：
- list/QVariantList 属性默认 ``[]``：QML 侧普遍直接读 ``.length``，
  ``null`` 会抛 TypeError
- Slot 返回类型化默认值：空函数返回 undefined，赋给 QString/int 属性
  会触发 "Cannot assign [undefined] to ..."
"""

from __future__ import annotations

from pathlib import Path

from .bridge_introspect import BridgeApi


_HEADER = """// AUTO-GENERATED by tools/ui_probe/mock_bridge.py — 请勿手改。
// 源：src/backend/presentation/bridge.py 的 QML 可见 API 面。
import QtQuick 2.15

QtObject {
"""

# 伪类型 "list" 渲染为 var，但默认值是 []（见模块 docstring）
_RENDER_TYPES = {"list": "var"}

_DEFAULTS = {
    "bool": "false",
    "int": "0",
    "real": "0.0",
    "string": '""',
    "var": "null",
    "list": "[]",
}

# slot 返回注解 -> QML 默认返回值；None 表示不返回（undefined）
_SLOT_RETURNS = {
    "str": '""',
    "bool": "false",
    "int": "0",
    "float": "0.0",
    "list": "[]",
    "dict": "({})",
    "None": None,
}


def render_mock_bridge(api: BridgeApi) -> str:
    """渲染 mock bridge QML 源码。"""
    parts: list[str] = [_HEADER]

    parts.append("    // ---- properties ----")
    for name in sorted(api.properties):
        qml_type = api.properties[name]
        render_type = _RENDER_TYPES.get(qml_type, qml_type)
        default = _DEFAULTS.get(qml_type, "null")
        parts.append(f"    property {render_type} {name}: {default}")

    parts.append("")
    parts.append("    // ---- slots ----")
    for name in sorted(api.slots):
        default = _SLOT_RETURNS.get(api.slots[name])
        if default is None:
            parts.append(f"    function {name}() {{}}")
        else:
            parts.append(f"    function {name}() {{ return {default} }}")

    parts.append("")
    parts.append("    // ---- signals ----")
    # 属性会隐式生成 <name>Changed 信号；显式声明会触发
    # "Duplicate signal name"（另避开 QtObject 内建 objectNameChanged/destroyed）
    implicit_change_signals = {f"{name}Changed" for name in api.properties}
    implicit_change_signals |= {"objectNameChanged", "destroyed"}
    for name in sorted(api.signals):
        if name in implicit_change_signals:
            continue
        arity = api.signals[name]
        params = ", ".join(f"var p{i}" for i in range(arity))
        parts.append(f"    signal {name}({params})")

    parts.append("}")
    return "\n".join(parts) + "\n"


def write_mock_bridge(api: BridgeApi, out_dir: Path) -> Path:
    """生成 mock bridge QML 到 out_dir，返回文件路径。"""
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "mock_bridge.qml"
    path.write_text(render_mock_bridge(api), encoding="utf-8")
    return path
